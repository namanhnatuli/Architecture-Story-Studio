"""Human-readable script + storyboard (with claim mapping and locked timing), generated
from narration.json, timing.json, storyboard.json and sources.json so it can never drift."""
import json
from pathlib import Path


def _fmt(t):
    return f"{int(t // 60)}:{t % 60:05.2f}"


def write(project_dir):
    p = Path(project_dir)
    narration = json.loads((p / "script/narration.json").read_text())
    timing = json.loads((p / "script/timing.json").read_text())
    story = json.loads((p / "storyboard/storyboard.json").read_text())
    claims = {c["id"]: c for c in json.loads((p / "research/sources.json").read_text())["claims"]}
    beats = {b["id"]: b for b in narration["beats"]}
    tbeats = {b["id"]: b for b in timing["beats"]}
    lines = [f"# {narration.get('title', p.name)} — script & storyboard (generated)",
             "",
             f"Generated by `python3 tools/cli.py schedule --project {p.name}` from the locked timing. Do not edit by hand.",
             f"Runtime {timing['total_seconds']:.3f} s ({timing['total_frames']} frames at {timing['fps']} fps); "
             f"timing locked: {timing['locked']}. Voice: {narration['voice']['id']} "
             f"({narration['voice']['license']['status']}). Status: {narration.get('status', '')}",
             "", "## Script", ""]
    for b in narration["beats"]:
        t = tbeats[b["id"]]
        lines.append(f"**{b['id']}** ({b['kind']}; claims {', '.join(b.get('claim_ids') or ['—'])}; "
                     f"{_fmt(t['start_seconds'])}, {t['duration']:.2f}s)")
        for s in t["sentences"]:
            lines.append(f"- `{_fmt(s['start'])}–{_fmt(s['end'])}` {s['text']}")
        lines.append("")
    lines += ["## Storyboard", "",
              "| Shot | Time | Beats | Template / states | What the picture shows (visual purpose) | Claims (status) |",
              "|---|---|---|---|---|---|"]
    for shot, t in zip(story["shots"], timing["shots"]):
        anim = shot.get("animation") or {}
        tmpl = anim.get("template") or shot.get("transition")
        states = anim.get("states") or [s for s in (shot.get("from_state"), shot.get("to_state")) if s]
        if shot.get("visual_type") == "MOTION_GRAPHICS":
            tmpl, states = "2D card (self-made)", []
        cl = ", ".join(f"{c} ({claims[c]['review_status']})" for c in shot.get("claim_ids", []))
        cut = " · hard cut in" if shot.get("cut_from_previous") == "hard" else ""
        lines.append(f"| {shot['id']} | {_fmt(t['start_seconds'])} +{t['duration_seconds']:.2f}s{cut} | "
                     f"{', '.join(t['beat_ids'])} | {tmpl} {' → '.join(dict.fromkeys(states))} | "
                     f"{shot['visual_purpose']} | {cl} |")
    lines += ["", "## Claims used", ""]
    for cid in sorted({c for b in narration["beats"] for c in b.get("claim_ids", [])}):
        c = claims[cid]
        lines.append(f"- **{cid}** ({c['review_status']}): {c['text']} — "
                     + "; ".join(f"{e['source_id']} {e['locator']}" for e in c.get("evidence", [])))
    out = p / "script" / "SCRIPT_AND_STORYBOARD.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
