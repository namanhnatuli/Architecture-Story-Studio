#!/usr/bin/env python3
"""Archived M4 pilot (M7: kept as a regression fixture). Regenerate
tests/fixtures/legacy_projects/bridge-structure-evolution/{storyboard/states.json, storyboard/storyboard.json,
project.json} from the library asset specs and the generators' exploded-view presets, so component
ids and explode distances can never drift from engine/arch.

    python3 tools/make_bridge_pilot.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from engine.arch import assets  # noqa: E402

P = ROOT / "tests" / "fixtures" / "legacy_projects" / "bridge-structure-evolution"   # archived pilot (M7)
B = "asset_library/architecture/bridges/"
SITE = "asset_library/architecture/sites/site_river_crossing_24.json"
VARIANTS = {"timber_beam": B + "bridge_timber_beam_01.json", "stone_arch": B + "bridge_stone_arch_03.json",
            "steel_truss": B + "bridge_steel_truss_pratt_01.json",
            "steel_truss_warren": B + "bridge_steel_truss_warren_01.json"}
CAMERA = "BRIDGE_THREE_QUARTER"


def ids(variant, *types):
    return [c.id for c in assets.plan_cached(VARIANTS[variant], variant) if c.type in types]


def pulse(components, strength):
    return {"components": components, "start_seconds": 0.7, "rise_seconds": 0.4, "hold_seconds": 1.1,
            "fall_seconds": 0.4, "strength": strength}


def exploded(variant, types, highlight, strength):
    return {"template": "EXPLODED_VIEW", "state": variant, "components": ids(variant, *types),
            "per_component": assets.explode_per_component(VARIANTS[variant], variant),
            "sequence": "SEQUENTIAL", "stagger_by": "LAYER", "order": "DISASSEMBLY", "stagger_seconds": 0.18,
            "hold_start_seconds": 0.4, "explode_seconds": 1.0, "hold_seconds": 1.4, "return_seconds": 1.0,
            "hold_end_seconds": 0.2,
            "highlight": {"components": highlight, "mode": "SIMULTANEOUS", "strength": strength, "fade_seconds": 0.25}}


def states():
    names = {"timber_beam": "Timber beam (trestle) bridge", "stone_arch": "Stone arch bridge (3 arches)",
             "steel_truss": "Steel pony truss, Pratt web", "steel_truss_warren": "Steel pony truss, Warren web on the same frame"}
    variants = []
    for vid, path in VARIANTS.items():
        v = {"id": vid, "name": names[vid], "builder": "architecture_asset", "asset": path}
        if vid == "steel_truss":
            v["claim_ids"] = ["CLM_001"]
        if vid == "steel_truss_warren":
            v.update(structure_from="steel_truss", claim_ids=["CLM_002"])
        variants.append(v)
    return {"schema_version": 2, "building_type": "bridge",
            "note": "M4 technical pilot: three illustrative bridge archetypes on one shared site. They are explanatory "
                    "archetypes, not a historical sequence. Generated by tools/make_bridge_pilot.py.",
            "base": {"builder": "architecture_asset", "asset": SITE}, "shared_components": ["banks", "water"],
            "variants": variants,
            "transitions": [{"from": "steel_truss", "to": "steel_truss_warren", "template": "REPLACE_PARTS"}]}


def shots():
    t_explode = {k: v for k, v in exploded("timber_beam", ("RAILING", "PLANK", "STRINGER", "CAP_BEAM"),
                                           ids("timber_beam", "STRINGER"), 0.4).items()}
    s_explode = exploded("stone_arch", ("COPING", "PARAPET", "DECK", "SPANDREL", "KEYSTONE", "VOUSSOIR"),
                         ids("stone_arch", "KEYSTONE"), 0.6)
    pratt_web = ids("steel_truss", "TRUSS_VERTICAL", "TRUSS_DIAGONAL")
    out = [
        dict(id="SC_001", duration_seconds=3.0, transition="HOLD", from_state="timber_beam", to_state="timber_beam",
             visual_purpose="Timber beam archetype: the primary beams (stringers) glow as they span between trestle bents; "
                            "the deck planks above them turn see-through meanwhile (M5 QA: otherwise 86% hidden).",
             animation={"template": "HOLD", "state": "timber_beam",
                        "highlight": dict(pulse(ids("timber_beam", "STRINGER"), 0.45), ghost=ids("timber_beam", "PLANK"),
                                          ghost_transparency=0.7)}),
        dict(id="SC_002", duration_seconds=5.5, transition="EXPLODED_VIEW", from_state="timber_beam", to_state="timber_beam",
             visual_purpose="Exploded timber deck: railings, planks, stringers and cap beams lift off the trestle posts to "
                            "show the load path, then return.", animation=t_explode),
        dict(id="SC_003", duration_seconds=3.0, transition="HOLD", cut_from_previous="hard", from_state="stone_arch",
             to_state="stone_arch", visual_purpose="Stone arch archetype on the same site: the voussoir rings and keystones glow.",
             animation={"template": "HOLD", "state": "stone_arch",
                        "highlight": pulse(ids("stone_arch", "VOUSSOIR", "KEYSTONE"), 0.4)}),
        dict(id="SC_004", duration_seconds=6.0, transition="EXPLODED_VIEW", from_state="stone_arch", to_state="stone_arch",
             visual_purpose="Exploded stone arch: coping, parapets and deck lift away and the spandrel fill slides back, "
                            "revealing the arch rings; each ring of wedge stones (voussoirs) opens slightly from its centre "
                            "and lifts off the piers, keystones glow; everything returns.", animation=s_explode),
        dict(id="SC_005", duration_seconds=3.0, transition="HOLD", cut_from_previous="hard", from_state="steel_truss",
             to_state="steel_truss", claim_ids=["CLM_001"],
             visual_purpose="Steel pony truss archetype on the same site: the Pratt web (verticals and diagonals sloping "
                            "down towards the centre) glows.",
             animation={"template": "HOLD", "state": "steel_truss", "highlight": pulse(pratt_web, 0.45)}),
        dict(id="SC_006", duration_seconds=4.0, transition="REPLACE_PARTS", from_state="steel_truss",
             to_state="steel_truss_warren", claim_ids=["CLM_001", "CLM_002"],
             visual_purpose="Compatible part replacement: on the same chords, deck and piers, the Pratt web lifts away and "
                            "a Warren web (alternating diagonals, no interior verticals) drops in.",
             animation={"template": "REPLACE_PARTS", "from_state": "steel_truss", "to_state": "steel_truss_warren",
                        "easing": "SMOOTH", "hold_start_seconds": 0.5, "hold_end_seconds": 0.8,
                        "outgoing": {"direction": "OUTWARD_UP", "distance": 2.6, "lift": 0.3, "lift_seconds": 0.3,
                                     "move_seconds": 1.0, "stagger_seconds": 0.08, "fade": True, "fade_start": 0.0},
                        "incoming": {"direction": "FROM_ABOVE", "distance": 2.2, "move_seconds": 1.1,
                                     "stagger_seconds": 0.08, "fade": True, "fade_end": 0.75, "overlap_seconds": 0.3,
                                     "easing": "EASE_OUT"}}),
        dict(id="SC_007", duration_seconds=5.0, transition="SIDE_BY_SIDE", cut_from_previous="hard", camera="BRIDGE_STACK",
             from_state="timber_beam", to_state="steel_truss",
             visual_purpose="Comparison of the three archetypes at identical scale on identical 24 m sites, stacked as rows "
                            "and captioned; they are alternatives, not a sequence.",
             animation={"template": "SIDE_BY_SIDE", "layout": "STACK", "states": ["timber_beam", "stone_arch", "steel_truss"],
                        "gap_ratio": 0.5, "label_band": 0.1,
                        "labels": {"timber_beam": "Timber beam", "stone_arch": "Stone arch", "steel_truss": "Steel truss (Pratt)"},
                        "highlight": {"components": "DIFFERENCES", "start_seconds": 1.4, "rise_seconds": 0.5,
                                      "hold_seconds": 1.6, "fall_seconds": 0.6, "strength": 0.3}}),
    ]
    t = 0.0
    for s in out:
        s.setdefault("camera", CAMERA)
        s.setdefault("claim_ids", [])
        s.update(start_seconds=round(t, 6), visual_type="BLENDER_3D", narration="")
        t += s["duration_seconds"]
    return out, t


def main():
    shot_list, total = shots()
    story = {"note": "M4 technical pilot (no narration): asset quality and engine integration, not a factual "
                     "documentary. Generated by tools/make_bridge_pilot.py; edit that script, not this file.",
             "key_stills": [{"id": "01_timber_overview", "shot": "SC_001", "time_seconds": 1.6},
                            {"id": "02_timber_exploded", "shot": "SC_002", "marker": "exploded_hold"},
                            {"id": "03_stone_overview", "shot": "SC_003", "time_seconds": 1.6},
                            {"id": "04_stone_exploded", "shot": "SC_004", "marker": "exploded_hold"},
                            {"id": "05_truss_pratt", "shot": "SC_005", "time_seconds": 1.6},
                            {"id": "06_truss_replace", "shot": "SC_006", "marker": "middle"},
                            {"id": "07_comparison", "shot": "SC_007", "time_seconds": 2.4}],
             "shots": shot_list}
    (P / "storyboard").mkdir(parents=True, exist_ok=True)
    (P / "storyboard/states.json").write_text(json.dumps(states(), indent=2) + "\n")
    (P / "storyboard/storyboard.json").write_text(json.dumps(story, indent=2) + "\n")
    project = {"slug": "bridge-structure-evolution",
               "title": "Bridge Structures — M4 Technical Pilot (illustrative archetypes)", "mode": "prototype",
               "language": "en", "fps": 24, "duration_seconds": total, "render_preset": "preview",
               "factual_review": "provisional", "audio_timing_locked": False,
               "production_profile": "TECHNICAL_SILENT_PREVIEW"}
    (P / "project.json").write_text(json.dumps(project, indent=2) + "\n")
    print(f"{len(shot_list)} shots, {total:.1f} s => {P}")


if __name__ == "__main__":
    main()
